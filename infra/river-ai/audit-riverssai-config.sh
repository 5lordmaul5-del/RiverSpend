#!/usr/bin/env bash
# Static configuration safety audit; no services started and no credentials read.
set -Eeuo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
COMPOSE="$HERE/docker-compose.yml"
fail(){ echo "FAIL: $*" >&2; exit 1; }
pass(){ echo "PASS: $*"; }
[[ -f "$COMPOSE" ]] || fail "compose file missing"
grep -Fq '127.0.0.1:8787:8787' "$COMPOSE" || fail "API must be loopback-bound"
pass "API binding is loopback-only"
if grep -Eq '(^|[[:space:]])ports:.*11434|11434:11434' "$COMPOSE"; then fail "Ollama port must not be published"; fi
pass "Ollama port not published"
grep -Fq 'riverdb_data:/var/lib/postgresql/data' "$COMPOSE" || fail "database named volume missing"
grep -Fq 'ollama_models:/root/.ollama' "$COMPOSE" || fail "model named volume missing"
pass "persistent volumes configured"
grep -Fq 'internal: true' "$COMPOSE" || fail "private internal network missing"
pass "internal network declaration present"
grep -Fq 'RIVER_AI_ADMIN_TOKEN' "$COMPOSE" || fail "admin token wiring missing"
grep -Fq 'RIVERDB_PASSWORD' "$COMPOSE" || fail "database password wiring missing"
pass "secret variables referenced (values are not checked by this static audit)"
grep -Fq 'health' "$COMPOSE" || fail "healthcheck missing"
pass "service healthcheck declaration present"

SERVER="$ROOT/server/river-ai-standalone.mjs"
DOCKERFILE="$HERE/Dockerfile"
[[ -f "$SERVER" ]] || fail "standalone server missing"
[[ -f "$DOCKERFILE" ]] || fail "Dockerfile missing"
grep -Fq 'MAX_BODY = 24 * 1024' "$SERVER" || fail "request body bound missing"
grep -Fq 'Formato memoria non valido.' "$SERVER" || fail "memory payload validation missing"
grep -Fq 'Math.min(50' "$SERVER" || fail "memory listing limit missing"
grep -Fq 'AbortSignal.timeout(90000)' "$SERVER" || fail "model request timeout missing"
grep -Fq 'MAX_ACTIVE_CHAT_REQUESTS' "$SERVER" || fail "global chat concurrency guard missing"
grep -Fq 'RIVER_AI_MAX_ACTIVE_CHAT_REQUESTS' "$COMPOSE" || fail "chat concurrency configuration wiring missing"
grep -Fq 'finally' "$SERVER" || fail "chat slot release finally block missing"
grep -Fq 'activeChatRequests >= MAX_ACTIVE_CHAT_REQUESTS' "$SERVER" || fail "active chat admission guard missing"
grep -Fq 'activeChatRequests += 1' "$SERVER" || fail "active chat slot increment missing"
grep -Fq 'activeChatRequests - 1' "$SERVER" || fail "active chat slot release missing"
grep -Fq 'timingSafeEqual' "$SERVER" || fail "timing-safe token comparison missing"
grep -Fq 'boundedInteger' "$SERVER" || fail "safe numeric environment parser missing"
grep -Fq 'Math.min(1000' "$SERVER" || fail "rate limit ceiling missing"
grep -Fq 'const limited = recent.length >= RATE_LIMIT' "$SERVER" || fail "rate limiter bounded behavior missing"
grep -Fq 'npm install --omit=dev pg@' "$DOCKERFILE" || fail "production dependency install missing"
pass "server input, request timeout, authentication comparison and runtime dependency checks present"

echo "STATIC CONFIG AUDIT PASS"
